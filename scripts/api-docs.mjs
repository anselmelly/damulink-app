// Builds docs/api-endpoints.md from the route files. Run: node scripts/api-docs.mjs
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'

const dir = 'apps/api/src/routes/'
// route file -> mount prefix and heading, from apps/api/src/app.ts (admin sub-routers are mounted inside admin.ts)
const MOUNTS = [
	['auth.ts', '/api/auth', 'Sign up and sign in'],
	['verification.ts', '/api/auth', 'Email and phone verification, password reset'],
	['facility-signup.ts', '/api/auth', 'Facility sign-up'],
	['invites.ts', '/api/invites', 'Team invitations'],
	['me.ts', '/api/me', 'My account (donor)'],
	['donor-calls.ts', '/api/donor/calls', 'Calls for a donor'],
	['facilities.ts', '/api/facilities', 'Facility search'],
	['requests.ts', '/api/requests', 'Blood requests (requester)'],
	['public-calls.ts', '/api/public/calls', 'Public calls (no login)'],
	['public-drives.ts', '/api/public/drives', 'Public blood drives (no login)'],
	['sms.ts', '/api/sms', 'SMS provider webhook'],
	['cron.ts', '/api/cron', 'Scheduled jobs'],
	['my-facilities.ts', '/api/my-facilities', 'My facilities and team'],
	['facility-home.ts', '/api/my-facilities/:id', 'Facility home and donors'],
	['facility-requests.ts', '/api/my-facilities/:id/requests', 'Facility: blood requests'],
	['facility-calls.ts', '/api/my-facilities/:id/calls', 'Facility: calls'],
	['drives.ts', '/api/my-facilities/:id/drives', 'Facility: blood drives'],
	['donor-requests.ts', '/api/my-facilities/:id/donor-requests', 'Facility: donor requests'],
	['records.ts', '/api/my-facilities/:id/records', 'Facility: donation records'],
	['checkin.ts', '/api/my-facilities/:id', 'Facility: check-in, lab results, walk-ins'],
	['admin.ts', '/api/admin', 'Super admin: facilities and verification'],
	['admin-system.ts', '/api/admin', 'Super admin: settings, admins, audit, misuse, dashboard'],
]
const known = new Set(MOUNTS.map((m) => m[0]))
for (const f of readdirSync(dir)) if (!known.has(f)) console.warn(`not in MOUNTS: ${f}`)

const out = ['# API endpoints', '', 'Generated by `node scripts/api-docs.mjs` from the route files; do not edit by hand. Conventions (auth, errors, formats) are in [api.md](api.md).', '', 'Auth column: **public** needs no login; **login** needs a valid `X-Auth` token; **super admin** needs a super admin. Facility routes also check that the caller belongs to the facility, and some need the facility admin or a permission.', '']
for (const [file, prefix, title] of MOUNTS) {
	const src = readFileSync(dir + file, 'utf8')
	const lines = src.split('\n')
	const fileAuth = /\.use\(\s*'[^']*'\s*,\s*requireAuth,\s*requireSuperAdmin/.test(src) ? 'super admin' : /\.use\(\s*'[^']*'\s*,\s*requireAuth\s*\)/.test(src) ? 'login' : null
	const rows = []
	lines.forEach((line, i) => {
		const m = line.match(/\w+\.(get|post|put|patch|delete)\(\s*'([^']*)'(.*)/)
		if (!m) return
		const auth = fileAuth ?? (/requireAuth/.test(m[3]) ? 'login' : 'public')
		let doc = ''
		for (let j = i - 1; j >= 0 && /^\s*(\/\/|\/\*\*|\*)/.test(lines[j]); j--) doc = lines[j].replace(/^\s*(\/\/|\/\*\*|\*\/|\*)\s?/, '').replace(/\*\/\s*$/, '').trim() + ' ' + doc
		rows.push(`| \`${m[1].toUpperCase()}\` | \`${prefix}${m[2] === '/' ? '' : m[2]}\` | ${auth} | ${doc.trim().replace(/\|/g, '\\|')} |`)
	})
	if (!rows.length) continue
	out.push(`## ${title}`, '', '| Method | Path | Auth | Notes |', '|---|---|---|---|', ...rows, '')
}
out.push('## Health', '', '| Method | Path | Auth | Notes |', '|---|---|---|---|', '| `GET` | `/api/health` | public | Checks the database and returns `{ ok, app, time }`. |', '')
writeFileSync('docs/api-endpoints.md', out.join('\n'))
console.log('wrote docs/api-endpoints.md')
